CREATE TABLE IF NOT EXISTS Artist (
    ArtistID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    Name VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS Songs (
    SongID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ArtistID INT REFERENCES Artist(ArtistID) ON DELETE CASCADE,
    Title VARCHAR(200) NOT NULL,
    AlbumName VARCHAR(200),
    Duration DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS FingerPrint (
    FingerPrint BIGINT NOT NULL,
    SongID INT NOT NULL REFERENCES Songs(SongID) ON DELETE CASCADE,
    AnchorFrame INTEGER NOT NULL,

    PRIMARY KEY (FingerPrint, SongID, AnchorFrame)
);

CREATE INDEX IF NOT EXISTS idx_fingerprint_hash
ON FingerPrint(FingerPrint);